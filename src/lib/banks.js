let _rng = Math.random
const useRng = (r) => {
  if (typeof r === 'function') _rng = r
}
const randInt = (min, max) => min + Math.floor(_rng() * (max - min + 1))
const pick = (arr) => arr[Math.floor(_rng() * arr.length)]
const fmt = (n) =>
  Number.isInteger(n) ? n.toLocaleString('en-US') : n.toLocaleString('en-US', { maximumFractionDigits: 2 })

export function shuffleWith(arr, rng) {
  const a = [...arr]
  for (let i = a.length - 1; i > 0; i -= 1) {
    const j = Math.floor(rng() * (i + 1))
    ;[a[i], a[j]] = [a[j], a[i]]
  }
  return a
}

const scramble = (rng, item) => {
  const correct = item.o[item.a ?? 0]
  const o = shuffleWith(item.o, rng)
  return { ...item, o, a: o.indexOf(correct), gen: true }
}

/* ---------- สร้างชุดคำถามตัวเลขจากเทมเพลต ---------- */
function buildNumeric(rng, templates, count, seen) {
  useRng(rng)
  const out = []
  let guard = 0
  while (out.length < count && guard < count * 30) {
    guard += 1
    const tpl = pick(templates)
    const q = tpl(rng)
    if (!q || !q.o || q.o.length !== 4) continue
    if (new Set(q.o.map(String)).size !== 4) continue
    if (seen.has(q.q)) continue
    seen.add(q.q)
    out.push(scramble(rng, q))
  }
  return out
}

