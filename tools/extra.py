DIFF_KEYS = (P1, P2)


def diff_note(key, stem, opts, idx):
    """ข้อเปรียบเทียบอักขระ: ชี้ตำแหน่งที่ตัวเลือกต่างจากโจทย์ให้ตรง ๆ"""
    if key not in DIFF_KEYS:
        return ''
    stem = (stem or '').strip()
    if len(stem) < 12 or len(opts) != 4 or not all(opts):
        return ''
    if not all(abs(len(o) - len(stem)) <= 2 for o in opts):
        return ''
    if sum(1 for o in opts if o[:6] == stem[:6]) < 3:
        return ''
    rows = []
    for i, o in enumerate(opts):
        if o == stem:
            rows.append('%s. ตรงกับโจทย์ทุกตัวอักษร' % 'กขคง'[i])
            continue
        pos = next((k for k in range(min(len(o), len(stem))) if o[k] != stem[k]), None)
        if pos is None:
            rows.append('%s. มีตัวอักษรเกิน/ขาดจากโจทย์ (โจทย์ %d ตัว ตัวเลือก %d ตัว)'
                        % ('กขคง'[i], len(stem), len(o)))
        else:
            rows.append('%s. ผิดที่ตัวอักษรตำแหน่งที่ %d (โจทย์ “%s” แต่ตัวเลือกเป็น “%s”)'
                        % ('กขคง'[i], pos + 1, stem[pos], o[pos]))
    rows.append('ต้องเลือกตัวเลือกที่เหมือนโจทย์ทุกตัวอักษร คือข้อ %s' % 'กขคง'[idx])
    return '\n'.join(rows) + '\n' + AI_NOTE


def build(key, num, stem, opts, idx):
    """คืนคำอธิบายเพิ่มเติม (มีหมายเหตุ AI ต่อท้าย) หรือ '' ถ้าไม่มี"""
    body = EXTRA.get(key, {}).get(num)
    if body:
        return body.strip() + '\n' + AI_NOTE
    return diff_note(key, stem, opts, idx)


